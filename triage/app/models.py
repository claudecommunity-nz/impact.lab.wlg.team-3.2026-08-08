class AuditAction(str, Enum):
    ingested = "ingested"
    triaged = "triaged"
    retriaged = "retriaged"
    viewed = "viewed"
    acknowledged = "acknowledged"
    priority_overridden = "priority_overridden"
    status_changed = "status_changed"
    marked_false = "marked_false"
    cluster_flagged_false = "cluster_flagged_false"
    note_added = "note_added"
    assigned = "assigned"
    forwarded = "forwarded"
    forward_failed = "forward_failed"
    linked_duplicate = "linked_duplicate"
    shift_started = "shift_started"
    shift_ended = "shift_ended"
    handover_generated = "handover_generated"
    config_changed = "config_changed"
    ruleset_generated = "ruleset_generated"


# Actions that represent a human decision, as opposed to machine bookkeeping.
# The handover briefing leads with these.
DECISION_ACTIONS = {
    AuditAction.priority_overridden, AuditAction.status_changed,
    AuditAction.marked_false, AuditAction.cluster_flagged_false,
    AuditAction.forwarded, AuditAction.note_added, AuditAction.assigned,
    AuditAction.linked_duplicate,
}


class AuditEvent(BaseModel):
    id: str = Field(default_factory=lambda: new_id("aud"))
    at: datetime = Field(default_factory=utcnow)
    reporting_id: Optional[str] = None
    shift_id: Optional[str] = None
    actor: str = "system"
    is_human: bool = True
    action: AuditAction
    field: Optional[str] = None
    from_value: Optional[str] = None
    to_value: Optional[str] = None
    note: Optional[str] = None
    detail: dict[str, Any] = Field(default_factory=dict)


class Shift(BaseModel):
    id: str = Field(default_factory=lambda: new_id("shf"))
    operator: str
    role: str = "Duty controller"
    started_at: datetime = Field(default_factory=utcnow)
    ended_at: Optional[datetime] = None
    handover_note: Optional[str] = None

    @property
    def is_open(self) -> bool:
        return self.ended_at is None


class Forward(BaseModel):
    id: str = Field(default_factory=lambda: new_id("fwd"))
    reporting_id: str
    destination_id: str
    destination_name: str
    transport: str            # "email" | "api"
    target: str               # address or URL
    note: Optional[str] = None
    sent_at: datetime = Field(default_factory=utcnow)
    sent_by: str = "system"
    shift_id: Optional[str] = None
    dry_run: bool = True
    ok: bool = True
    response: Optional[str] = None
    payload: dict[str, Any] = Field(default_factory=dict)
    acknowledged_at: Optional[datetime] = Field(
        default=None,
        description="Set when the receiving agency confirms. Until then the "
                    "handover briefing lists this as awaiting a reply.")
