class MediaItem(BaseModel):
    kind: MediaKind = MediaKind.image
    url: Optional[str] = None
    thumbnail_url: Optional[str] = None
    caption: Optional[str] = None
    caption_source: Optional[CaptionSource] = None
    model_caption: Optional[str] = Field(
        default=None,
        description="Caption generated by a vision model. Always rendered with "
                    "an 'AI-generated' label — never shown as the author's words.",
    )
    mime_type: Optional[str] = None
    captured_at: Optional[datetime] = None


class SourceRef(BaseModel):
    """Where this came from, and how far we can trust the channel itself."""
    channel: Channel = Channel.other
    system: Optional[str] = Field(
        default=None, description="Originating system, e.g. 'WCC Contact Centre', 'x'.")
    external_id: Optional[str] = Field(
        default=None, description="Stable id in the origin system. Used to reject duplicates on re-ingest.")
    permalink: Optional[str] = Field(
        default=None, description="Link back to the original. The problem statement "
                                  "requires we never lose this.")
    author_handle: Optional[str] = None
    author_display_name: Optional[str] = None
    received_at: datetime = Field(default_factory=utcnow)
    ingested_by: Optional[str] = Field(
        default=None, description="Which pipeline/team pushed this in.")
    credibility_hint: Optional[float] = Field(
        default=None, ge=0.0, le=1.0,
        description="Optional upstream credibility score. Advisory only.")


class Content(BaseModel):
    text: Optional[str] = None
    transcript: Optional[str] = Field(
        default=None, description="Call-centre call transcript, verbatim.")
    subject: Optional[str] = None
    summary: Optional[str] = Field(
        default=None, description="Machine summary. Labelled as such in the UI.")
    language: str = "en"
    media: list[MediaItem] = Field(default_factory=list)

    def searchable(self) -> str:
        parts = [self.subject, self.text, self.transcript]
        parts += [m.caption for m in self.media if m.caption]
        parts += [m.model_caption for m in self.media if m.model_caption]
        return "\n".join(p for p in parts if p)


class LocationHint(BaseModel):
    text: Optional[str] = Field(
        default=None, description="Location as the person described it.")
    lat: Optional[float] = None
    lon: Optional[float] = None
    accuracy_m: Optional[float] = None
    method: GeoMethod = GeoMethod.unknown
    suburb: Optional[str] = None
    confidence: Optional[float] = Field(default=None, ge=0.0, le=1.0)

    @property
    def has_coords(self) -> bool:
        return self.lat is not None and self.lon is not None

    @property
    def is_precise(self) -> bool:
        return self.has_coords and self.method.is_precise


class Reporter(BaseModel):
    """Contact details. Kept out of the repo's seed data — the demo corpus uses
    invented names and dummy addresses only."""
    name: Optional[str] = None
    phone: Optional[str] = None
    email: Optional[str] = None
    organisation: Optional[str] = None
    is_official: bool = False


class Signal(BaseModel):
    """One rule that fired, kept so the operator can see *why* a priority was
    assigned. This is what makes the triage assistive rather than a black box."""
    rule_id: str
    label: str
    score: float
    rationale: Optional[str] = None


class TriageResult(BaseModel):
    priority: Priority = Priority.situational_awareness
    score: float = 0.0
    category: str = "general"
    category_label: str = "General"
    confidence: float = 0.5
    rationale: str = ""
    signals: list[Signal] = Field(default_factory=list)
    engine: EngineMode = EngineMode.rules
    ruleset_version: Optional[int] = None
    model: Optional[str] = None
    # Set when the ruleset and the LLM disagreed. Surfaced in the UI rather
    # than silently resolved — the operator decides.
    disagreement: Optional[str] = None
    llm_priority: Optional[Priority] = None
    llm_rationale: Optional[str] = None
    computed_at: datetime = Field(default_factory=utcnow)


class Reporting(BaseModel):
    """The canonical record."""
    id: str = Field(default_factory=lambda: new_id("rpt"))
    source: SourceRef = Field(default_factory=SourceRef)
    content: Content = Field(default_factory=Content)
    occurred_at: Optional[datetime] = None
    location: Optional[LocationHint] = None
    reporter: Optional[Reporter] = None
    tags: list[str] = Field(default_factory=list)
    raw: dict[str, Any] = Field(
        default_factory=dict,
        description="The original payload, verbatim. Never modified.")

    # --- assigned by us -----------------------------------------------------
    triage: Optional[TriageResult] = None
    priority: Priority = Priority.situational_awareness
    priority_overridden: bool = False
    override_reason: Optional[str] = None
    status: Status = Status.new
    cluster_id: Optional[str] = None
    duplicate_of: Optional[str] = None

    # --- shift-handover critical fields ------------------------------------
    acknowledged_by: Optional[str] = Field(
        default=None, description="First human to open this. If null at end of "
                                  "shift, nobody has looked at it — the exact "
                                  "miss the handover briefing must catch.")
    acknowledged_at: Optional[datetime] = None
    assigned_to: Optional[str] = None
    ingested_at: datetime = Field(default_factory=utcnow)
    updated_at: datetime = Field(default_factory=utcnow)
    ingest_shift_id: Optional[str] = None

    def effective_text(self) -> str:
        return self.content.searchable()


class IngestResult(BaseModel):
    accepted: int = 0
    duplicates_rejected: int = 0
    ids: list[str] = Field(default_factory=list)
    errors: list[str] = Field(default_factory=list)


