"""Canonical schema for an incoming disaster reporting.

A "reporting" is one thing a person (or an agency, or a sensor) told us —
typically a call-centre call, but equally an email, a form submission, a social
post or a partner-agency update. Everything downstream (triage, dedupe, map,
audit, handover) operates on this shape.

Two rules the schema enforces on purpose:

1. `source.permalink` and `raw` are always preserved, so an operator can get
   back to the original words. Nothing we infer replaces what was actually said.
2. Anything the machine derived lives under `triage`, never mixed into
   `content`. The UI can therefore always show "what came in" separately from
   "what we think about it".
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Optional

from pydantic import BaseModel, Field


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


def new_id(prefix: str) -> str:
    return f"{prefix}_{uuid.uuid4().hex[:12]}"


# ---------------------------------------------------------------------------
# Enumerations
# ---------------------------------------------------------------------------


class Channel(str, Enum):
    phone_call = "phone_call"
    email = "email"
    web_form = "web_form"
    social_media = "social_media"
    news = "news"
    partner_agency = "partner_agency"
    sensor = "sensor"
    other = "other"


class MediaKind(str, Enum):
    image = "image"
    video = "video"
    audio = "audio"
    document = "document"


class CaptionSource(str, Enum):
    author = "author"      # the person who filed it wrote this
    operator = "operator"  # a staff member wrote this
    model = "model"        # generated — must be labelled as such in the UI


class GeoMethod(str, Enum):
    device_gps = "device_gps"
    user_pin = "user_pin"
    operator = "operator"
    post_geotag = "post_geotag"
    profile = "profile"
    gazetteer = "gazetteer"       # we matched a place name in free text
    text_inference = "text_inference"
    unknown = "unknown"

    @property
    def is_precise(self) -> bool:
        return self in (GeoMethod.device_gps, GeoMethod.user_pin,
                        GeoMethod.post_geotag, GeoMethod.operator)


class Priority(str, Enum):
    """The three buckets the problem statement asks for."""
    action_required = "action_required"
    verification_required = "verification_required"
    situational_awareness = "situational_awareness"


PRIORITY_RANK = {
    Priority.situational_awareness: 0,
    Priority.verification_required: 1,
    Priority.action_required: 2,
}

PRIORITY_LABEL = {
    Priority.action_required: "Action required",
    Priority.verification_required: "Verification required",
    Priority.situational_awareness: "Situational awareness",
}


class Status(str, Enum):
    """Workflow state. Distinct from priority — a reporting can be
    `action_required` and still `new` (nobody has picked it up yet), which is
    exactly the thing a shift handover has to surface."""
    new = "new"
    acknowledged = "acknowledged"
    in_review = "in_review"
    verified = "verified"
    false_reporting = "false_reporting"
    forwarded = "forwarded"
    actioned = "actioned"
    closed = "closed"
    duplicate = "duplicate"


OPEN_STATUSES = {Status.new, Status.acknowledged, Status.in_review,
                 Status.verified, Status.forwarded}


class EngineMode(str, Enum):
    rules = "rules"
    llm = "llm"
    hybrid = "hybrid"


